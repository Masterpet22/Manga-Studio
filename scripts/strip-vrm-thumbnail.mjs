import fs from 'node:fs';

const input=process.argv[2];
const output=process.argv[3];
if(!input||!output)throw new Error('Usage: node strip-vrm-thumbnail.mjs INPUT OUTPUT');
const file=fs.readFileSync(input);
if(file.readUInt32LE(0)!==0x46546c67||file.readUInt32LE(4)!==2)throw new Error('Expected a GLB/VRM 2.0 file');
const jsonLength=file.readUInt32LE(12);
const json=JSON.parse(file.subarray(20,20+jsonLength).toString('utf8'));
const binHeader=20+jsonLength;
if(file.readUInt32LE(binHeader+4)!==0x004e4942)throw new Error('Expected a BIN chunk');
const bin=file.subarray(binHeader+8,binHeader+8+file.readUInt32LE(binHeader));
const meta=json.extensions?.VRMC_vrm?.meta;
const imageIndex=meta?.thumbnailImage;
if(imageIndex!==json.images.length-1)throw new Error('Thumbnail must be the final image');
const viewIndex=json.images[imageIndex].bufferView;
if(viewIndex!==json.bufferViews.length-1)throw new Error('Thumbnail must use the final buffer view');
const view=json.bufferViews[viewIndex];
if(view.byteOffset+view.byteLength>bin.length)throw new Error('Invalid thumbnail buffer range');
delete meta.thumbnailImage;
json.images.pop();
json.bufferViews.pop();
json.buffers[0].byteLength=view.byteOffset;
let jsonBuffer=Buffer.from(JSON.stringify(json));
const jsonPadding=(4-jsonBuffer.length%4)%4;
jsonBuffer=Buffer.concat([jsonBuffer,Buffer.alloc(jsonPadding,0x20)]);
let binBuffer=bin.subarray(0,view.byteOffset);
const binPadding=(4-binBuffer.length%4)%4;
binBuffer=Buffer.concat([binBuffer,Buffer.alloc(binPadding)]);
const result=Buffer.alloc(12+8+jsonBuffer.length+8+binBuffer.length);
result.writeUInt32LE(0x46546c67,0);result.writeUInt32LE(2,4);result.writeUInt32LE(result.length,8);
result.writeUInt32LE(jsonBuffer.length,12);result.writeUInt32LE(0x4e4f534a,16);jsonBuffer.copy(result,20);
const next=20+jsonBuffer.length;result.writeUInt32LE(binBuffer.length,next);result.writeUInt32LE(0x004e4942,next+4);binBuffer.copy(result,next+8);
fs.writeFileSync(output,result);
console.log(`${output}: ${result.length} bytes`);
